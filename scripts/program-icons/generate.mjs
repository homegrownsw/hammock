// Generates the program icon tables from icons.json:
//   apple/Sources/HammockKit/ProgramIconData.swift  (Mac and iPhone: paths and SF Symbols)
//   internal/tui/programicons_gen.go            (TUI: Nerd Font glyphs)
// Simple Icons' paths are flattened to absolute M, L, H, V, C and Z (what
// HammockKit's SVGPath reads). Run with `just program-icons`.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import svgpath from 'svgpath';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '../..');
const { icons, programs } = JSON.parse(fs.readFileSync(path.join(here, 'icons.json'), 'utf8'));
const glyphnames = JSON.parse(fs.readFileSync(process.argv[2] ?? path.join(here, "node_modules/.glyphnames-3.3.0.json"), 'utf8'));
const siVersion = JSON.parse(fs.readFileSync(path.join(here, 'node_modules/simple-icons/package.json'), 'utf8')).version;

const fail = msg => { console.error(msg); process.exit(1); };

// Brand colours, by Simple Icons slug.
const brand = Object.fromEntries(Object.values(await import('simple-icons')).filter(i => i?.slug).map(i => [i.slug, i.hex]));

// A glyph colour that reads on bg: white, as app icons have it, but
// near-black on light colours (WCAG relative luminance over 0.4: yellows,
// light greens), where white would wash out.
function contrast(bg) {
  const lin = c => (c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4);
  const [r, g, b] = [0, 2, 4].map(i => lin(parseInt(bg.slice(i, i + 2), 16) / 255));
  const l = 0.2126 * r + 0.7152 * g + 0.0722 * b;
  return l > 0.4 ? '1D1D1F' : 'FFFFFF';
}

function num(n) {
  let s = n.toFixed(3).replace(/\.?0+$/, '');
  if (s === '-0' || s === '') s = '0';
  return s;
}

// Absolute, no arcs or shorthands, quadratics raised to cubics.
function flatten(d) {
  const out = [];
  svgpath(d).abs().unarc().unshort().iterate((s, _i, x, y) => {
    const [cmd, ...a] = s;
    switch (cmd) {
      case 'M': case 'L': case 'H': case 'V': case 'C':
        out.push(cmd + a.map(num).join(' '));
        break;
      case 'Q': {
        const [qx, qy, ex, ey] = a;
        const c = [x + (2 / 3) * (qx - x), y + (2 / 3) * (qy - y), ex + (2 / 3) * (qx - ex), ey + (2 / 3) * (qy - ey), ex, ey];
        out.push('C' + c.map(num).join(' '));
        break;
      }
      case 'Z': case 'z':
        out.push('Z');
        break;
      default:
        fail(`unexpected path command ${cmd}`);
    }
  });
  return out.join('');
}

const swiftGlyphs = [];
const swiftColors = [];
const goGlyphs = [];
for (const key of Object.keys(icons).sort()) {
  const icon = icons[key];
  if (icon.simple) {
    const file = path.join(here, 'node_modules/simple-icons/icons', `${icon.simple}.svg`);
    if (!fs.existsSync(file)) fail(`${key}: no Simple Icon ${icon.simple}`);
    const d = fs.readFileSync(file, 'utf8').match(/<path d="([^"]+)"/)?.[1];
    if (!d) fail(`${key}: no path in ${icon.simple}.svg`);
    swiftGlyphs.push(`        "${key}": .path("${flatten(d)}"),`);
  } else if (icon.symbol) {
    swiftGlyphs.push(`        "${key}": .symbol("${icon.symbol}"),`);
  } else {
    fail(`${key}: neither simple nor symbol`);
  }
  const bg = icon.bg ?? (icon.simple && brand[icon.simple]);
  if (!/^[0-9A-F]{6}$/i.test(bg ?? '')) fail(`${key}: no bg colour (an SF Symbol needs one)`);
  const fg = icon.fg ?? contrast(bg);
  swiftColors.push(`        "${key}": .init(background: 0x${bg.toUpperCase()}, foreground: 0x${fg.toUpperCase()}),`);
  if (icon.nerd) {
    const g = glyphnames[icon.nerd];
    if (!g) fail(`${key}: no Nerd Font glyph ${icon.nerd}`);
    const esc = g.code.length > 4 ? '\\U' + g.code.padStart(8, '0') : '\\u' + g.code.padStart(4, '0');
    goGlyphs.push(`\t${JSON.stringify(key)}: '${esc}', // ${icon.nerd}`);
  }
}

const progs = Object.keys(programs).sort();
for (const p of progs) if (!icons[programs[p]]) fail(`program ${p}: no icon ${programs[p]}`);

const swift = `// Generated by scripts/program-icons/generate.mjs from icons.json
// (\`just program-icons\`). Don't edit by hand.
//
// Paths: Simple Icons ${siVersion} (simpleicons.org), CC0 1.0. The logos
// themselves are their makers' trademarks, used to name their products.

extension ProgramIcon {
    /// The icon each program shows, by the name the daemon reports.
    static let builtInPrograms: [String: String] = [
${progs.map(p => `        ${JSON.stringify(p)}: ${JSON.stringify(programs[p])},`).join('\n')}
    ]

    /// Each icon's art: a Simple Icons path (24×24) or an SF Symbol.
    static let builtInGlyphs: [String: Glyph] = [
${swiftGlyphs.join('\n')}
    ]

    /// Each icon's colours in the colourful style: its squircle and glyph
    /// (0xRRGGBB), from the brand's where there's one.
    static let builtInColors: [String: Colors] = [
${swiftColors.join('\n')}
    ]
}
`;

const goSrc = `// Code generated by scripts/program-icons/generate.mjs from icons.json; DO NOT EDIT.

package tui

// programIcons is the icon each program shows, by the name the daemon reports.
var programIcons = map[string]string{
${progs.map(p => `\t${JSON.stringify(p)}: ${JSON.stringify(programs[p])},`).join('\n')}
}

// nerdGlyphs is each icon's Nerd Font glyph (Nerd Fonts 3.3 names).
var nerdGlyphs = map[string]rune{
${goGlyphs.join('\n')}
}
`;

fs.writeFileSync(path.join(root, 'apple/Sources/HammockKit/ProgramIconData.swift'), swift);
fs.writeFileSync(path.join(root, 'internal/tui/programicons_gen.go'), goSrc);
console.log(`${Object.keys(icons).length} icons, ${progs.length} programs`);
