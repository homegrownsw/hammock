// Command docsgen makes the docs site's reference pages from Hammock's own
// sources, so they can't drift from it (`just docs-gen` runs it):
//
//	docsgen swift-header                  write the Mac app's config header (ConfigHeader.generated.swift)
//	docsgen pages DIR HELP MCP KEYBINDS   write DIR/{config,agents,cli,mcp,keyboard-shortcuts}.md
//
// HELP is `hmk help`'s output, MCP is `hmk mcp --list-tools`'s and KEYBINDS
// the keybinds dump's (site/gen/keybinds).
package main

import (
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"slices"
	"sort"
	"strings"

	"github.com/homegrownsw/hammock/internal/agents"
	"github.com/homegrownsw/hammock/internal/hammockconfig"
)

func main() {
	if err := run(os.Args[1:]); err != nil {
		fmt.Fprintln(os.Stderr, "docsgen:", err)
		os.Exit(1)
	}
}

func run(args []string) error {
	switch {
	case len(args) == 1 && args[0] == "swift-header":
		return os.WriteFile("apple/Sources/HammockMac/ConfigHeader.generated.swift", []byte(hammockconfig.SwiftHeaderFile()), 0o644)
	case len(args) == 5 && args[0] == "pages":
		dir := args[1]
		help, err := os.ReadFile(args[2])
		if err != nil {
			return err
		}
		mcp, err := os.ReadFile(args[3])
		if err != nil {
			return err
		}
		keys, err := os.ReadFile(args[4])
		if err != nil {
			return err
		}
		pages := map[string]func() (string, error){
			"config.md":             func() (string, error) { return configPage(), nil },
			"agents.md":             func() (string, error) { return agentsPage(), nil },
			"cli.md":                func() (string, error) { return cliPage(string(help)) },
			"mcp.md":                func() (string, error) { return mcpPage(mcp) },
			"keyboard-shortcuts.md": func() (string, error) { return shortcutsPage(keys) },
		}
		if err := os.MkdirAll(dir, 0o755); err != nil {
			return err
		}
		for name, make := range pages {
			s, err := make()
			if err != nil {
				return fmt.Errorf("%s: %w", name, err)
			}
			if err := os.WriteFile(filepath.Join(dir, name), []byte(s), 0o644); err != nil {
				return err
			}
		}
		return nil
	}
	return fmt.Errorf("usage: docsgen swift-header | pages DIR HELP MCP KEYBINDS")
}

const generated = "<!-- Generated by scripts/docsgen from Hammock's source: don't edit. -->\n\n"

func frontmatter(title, description string, order int) string {
	return fmt.Sprintf("---\ntitle: %s\ndescription: %s\nsidebar:\n  order: %d\n---\n\n", yamlQuote(title), yamlQuote(description), order)
}

func yamlQuote(s string) string { b, _ := json.Marshal(s); return string(b) }

// cell makes text safe in a Markdown table cell (and in Markdown generally).
func cell(s string) string {
	s = strings.ReplaceAll(s, "\n", " ")
	s = strings.ReplaceAll(s, "|", `\|`)
	return text(s)
}

// text escapes what Markdown/MDX would read as HTML or expressions, outside code spans.
func text(s string) string {
	parts := strings.Split(s, "`")
	for i := 0; i < len(parts); i += 2 {
		r := strings.NewReplacer("<", "&lt;", ">", "&gt;", "{", "&#123;", "}", "&#125;")
		parts[i] = r.Replace(parts[i])
	}
	return strings.Join(parts, "`")
}

// sentence: a capital first letter and a full stop.
func sentence(s string) string {
	s = strings.TrimSpace(s)
	if s == "" {
		return s
	}
	if s[0] >= 'a' && s[0] <= 'z' {
		s = strings.ToUpper(s[:1]) + s[1:]
	}
	if !strings.HasSuffix(s, ".") {
		s += "."
	}
	return s
}

func code(s string) string {
	if strings.Contains(s, "`") {
		return "`` " + s + " ``"
	}
	return "`" + s + "`"
}

func slug(s string) string {
	s = strings.ToLower(s)
	s = regexp.MustCompile(`[^a-z0-9]+`).ReplaceAllString(s, "-")
	return strings.Trim(s, "-")
}

// ---- The config file

func configPage() string {
	var b strings.Builder
	b.WriteString(frontmatter("Config file reference", "Every key Hammock's config file can hold, with its default.", 2))
	b.WriteString(generated)
	b.WriteString("Hammock's settings live in `~/.config/hammock/config`, in [Ghostty's syntax](https://ghostty.org/docs/config): one `key = value` per line, `#` for comments. ")
	b.WriteString("Settings writes the same keys, and changes you make to the file apply within a couple of seconds. ")
	b.WriteString("A key you leave out takes its default. See [Configuration](/hammock/docs/configuration/) for how the file works.\n\n")
	b.WriteString("Keys marked *Mac only*, *hmk tui only* or *Mac and hmk tui only* are read there alone; the rest are read by the Mac app, `hmk tui` and the Hammock Server wherever they make sense. The iPhone app keeps its own settings, on the phone, in its Settings tab.\n\n")
	for _, g := range hammockconfig.Groups {
		fmt.Fprintf(&b, "## %s\n\n", g)
		for _, k := range hammockconfig.Keys {
			if k.Group != g {
				continue
			}
			fmt.Fprintf(&b, "### %s\n\n", k.Name)
			var meta []string
			if k.Default != "" {
				meta = append(meta, "Default: "+code(k.Default))
			}
			if strings.Contains(k.Value, " | ") {
				meta = append(meta, "Values: "+code(k.Value))
			} else if k.Default == "" || k.Value != k.Default {
				meta = append(meta, "Example: "+code(k.Value))
			}
			if k.Repeat {
				meta = append(meta, "Repeatable")
			}
			if k.Only != "" {
				meta = append(meta, "*"+k.Only+" only*")
			}
			if len(meta) > 0 {
				b.WriteString(strings.Join(meta, " · ") + "\n\n")
			}
			if k.Doc != "" {
				b.WriteString(text(sentence(k.Doc)) + "\n\n")
			}
			if k.Example != "" {
				b.WriteString("```ini\n" + k.Example + "\n```\n\n")
			}
		}
	}
	return b.String()
}

// ---- The agents

func agentsPage() string {
	var b strings.Builder
	b.WriteString(frontmatter("Supported agents", "The coding agents Hammock knows, and what it can do with each.", 3))
	b.WriteString(generated)
	b.WriteString("Hammock recognises these agents in any pane. The columns say what it can do with each; see [Agents](/hammock/docs/agents/overview/) for what they mean. The ID is how config keys, schedules and `hmk hooks install --harness` name it.\n\n")
	b.WriteString("| Agent | ID | Command | Hooks | Agent view | Session finder | Resume | Start with a message | Schedules | Usage limits |\n")
	b.WriteString("|---|---|---|---|---|---|---|---|---|---|\n")
	yes := func(v bool) string {
		if v {
			return "✓"
		}
		return "–"
	}
	all := slices.Clone(agents.All)
	sort.SliceStable(all, func(i, j int) bool { return all[i].Order < all[j].Order })
	for _, a := range all {
		start := "✓"
		if a.TypePrompt {
			start = "typed in"
		}
		usage := "–"
		switch {
		case a.Usage != nil:
			usage = "✓"
		case a.LiveUsage != nil:
			usage = "asked"
		}
		fmt.Fprintf(&b, "| %s | `%s` | `%s` | %s | %s | %s | %s | %s | %s | %s |\n", cell(a.Name), a.ID, a.Command, yes(a.Hooks),
			yes(a.NewParser != nil), yes(a.Sessions != nil), yes(a.Resume != nil), start, yes(a.Schedulable), usage)
	}
	b.WriteString("\n")
	b.WriteString("- **Hooks:** `hmk hooks install` can set up hooks, so the agent tells Hammock exactly what it's doing. Without them, Hammock reads its process and screen.\n")
	b.WriteString("- **Agent view:** Hammock can show its conversation as a native, readable view, beside or instead of its terminal.\n")
	b.WriteString("- **Session finder:** its past sessions can be searched (`hmk sessions`) and resumed (`hmk resume`).\n")
	b.WriteString("- **Start with a message: typed in:** it takes no first message on its command line, so Hammock starts it and types the message once it's ready.\n")
	b.WriteString("- **Usage limits:** ✓ is read from what the agent keeps on disk; *asked* is asked of the agent's own service, only with `usage-live = true`.\n")
	return b.String()
}

// ---- The CLI

type cliEntry struct {
	sig  []string
	desc []string
}

// cliSections puts each command (its first word) on a page section.
var cliSections = []struct {
	title, blurb string
	cmds         []string
}{
	{"Workspace", "Groups, tabs and panes, and what's in them.", []string{"ls", "focus", "group", "tab", "split", "float", "dock", "minimise", "floats", "close", "reopen", "attach", "send", "read", "theme"}},
	{"Browser, simulator, log, editor and diff panes", "Panes that aren't terminals.", []string{"browser", "nav", "devtools", "show", "sim", "log", "edit", "diff", "review"}},
	{"Agents", "Starting, finding and resuming agents, and what they may do.", []string{"agent", "switch", "sleep", "wake", "session-link", "sessions", "resume", "grant", "audit", "schedule", "hook", "hooks", "mcp"}},
	{"Devices, linked computers and sharing", "Your iPhone, your other computers, and other people.", []string{"remote", "pair", "devices", "link", "computers", "share", "approve", "unshare", "join", "leave"}},
	{"Keys and SSH", "The Hammock Key, and SSH in Hammock's panes.", []string{"key", "ssh"}},
	{"The Hammock Server, the TUI and more", "Running Hammock itself.", []string{"tui", "stop", "status", "service", "docs", "acknowledgements"}},
}

func parseHelp(help string) (entries []cliEntry, footer []string, err error) {
	lines := strings.Split(help, "\n")
	inUsage, inFooter := false, false
	const descCol = 44
	gap := regexp.MustCompile(`\S(\s{2,})\S`)
	for _, l := range lines {
		switch {
		case strings.HasPrefix(l, "Usage:"):
			inUsage = true
			continue
		case inFooter:
			if t := strings.TrimSpace(l); t != "" {
				footer = append(footer, t)
			}
			continue
		case !inUsage:
			continue
		case strings.HasPrefix(l, "  hmk "):
			body := l[2:]
			e := cliEntry{}
			if loc := gap.FindStringSubmatchIndex(body); loc != nil && loc[3] >= 20 {
				e.sig = append(e.sig, strings.TrimSpace(body[:loc[2]]))
				e.desc = append(e.desc, strings.TrimSpace(body[loc[3]:]))
			} else {
				e.sig = append(e.sig, strings.TrimSpace(body))
			}
			entries = append(entries, e)
		case strings.TrimSpace(l) == "":
			if len(entries) > 0 {
				inUsage, inFooter = false, true
			}
			continue
		case len(entries) > 0 && len(l)-len(strings.TrimLeft(l, " ")) >= descCol-2:
			entries[len(entries)-1].desc = append(entries[len(entries)-1].desc, strings.TrimSpace(l))
		case len(entries) > 0 && strings.HasPrefix(l, " "):
			entries[len(entries)-1].sig = append(entries[len(entries)-1].sig, strings.TrimSpace(l))
		}
	}
	if len(entries) < 20 {
		return nil, nil, fmt.Errorf("found only %d commands in hmk help: has its layout changed?", len(entries))
	}
	return entries, footer, nil
}

func cliPage(help string) (string, error) {
	entries, footer, err := parseHelp(help)
	if err != nil {
		return "", err
	}
	byCmd := map[string][]cliEntry{}
	var order []string
	for _, e := range entries {
		cmd := strings.Fields(e.sig[0])[1]
		if _, ok := byCmd[cmd]; !ok {
			order = append(order, cmd)
		}
		byCmd[cmd] = append(byCmd[cmd], e)
	}
	var b strings.Builder
	b.WriteString(frontmatter("CLI reference", "Every hmk command and its options, from hmk help.", 4))
	b.WriteString(generated)
	b.WriteString("`hmk` is Hammock's command line: it works from any terminal on a Mac or Linux machine running the Hammock Server (see [The CLI](/hammock/docs/cli/) for installing it). ")
	b.WriteString("This page is `hmk help`, sorted. For a guided tour, see [The CLI](/hammock/docs/cli/).\n\n")
	b.WriteString(":::note\n" + text(strings.Join(footer, " ")) + "\n:::\n\n")
	placed := map[string]bool{}
	section := func(title, blurb string, cmds []string) {
		fmt.Fprintf(&b, "## %s\n\n%s\n\n", title, blurb)
		for _, c := range cmds {
			es, ok := byCmd[c]
			if !ok {
				continue
			}
			placed[c] = true
			fmt.Fprintf(&b, "### hmk %s\n\n", c)
			for _, e := range es {
				b.WriteString("```sh\n" + strings.Join(e.sig, "\n    ") + "\n```\n\n")
				if len(e.desc) > 0 {
					b.WriteString(text(sentence(strings.Join(e.desc, " "))) + "\n\n")
				}
			}
		}
	}
	for _, s := range cliSections {
		section(s.title, s.blurb, s.cmds)
	}
	var rest []string
	for _, c := range order {
		if !placed[c] {
			rest = append(rest, c)
		}
	}
	if len(rest) > 0 {
		section("More", "Other commands.", rest)
	}
	return b.String(), nil
}

// ---- MCP

type mcpList struct {
	Instructions string `json:"instructions"`
	Tools        []struct {
		Group       string `json:"group"`
		Name        string `json:"name"`
		Description string `json:"description"`
		InputSchema struct {
			Properties map[string]struct {
				Type        any    `json:"type"`
				Description string `json:"description"`
				Items       *struct {
					Type any `json:"type"`
				} `json:"items"`
			} `json:"properties"`
			Required []string `json:"required"`
		} `json:"inputSchema"`
	} `json:"tools"`
}

var mcpGroups = []struct{ id, title, blurb string }{
	{"panes", "Panes", "Reading the workspace, and opening, driving and closing panes."},
	{"browser", "Browser panes", "Real Chromium pages you can see, for checking a dev server or a page. `show_output` opens a file or page in one."},
	{"simulator", "Simulator panes", "iOS simulators, to install, launch, look at and drive apps."},
	{"log", "Log panes", "A file, the Mac's or a simulator's log, logcat or a command, parsed into entries."},
	{"editor", "Editor panes", "Point you at code, and read what you have open and selected."},
	{"diff", "Diff panes and reviews", "Open a diff for you to review, and answer your comments on it."},
	{"sessions", "Agent sessions", "Search and read agents' past sessions on this Mac."},
	{"schedules", "Scheduled tasks", "Agent prompts and commands that run on a schedule."},
}

func typeName(t any, items *struct {
	Type any `json:"type"`
}) string {
	switch v := t.(type) {
	case string:
		if v == "array" && items != nil {
			return typeName(items.Type, nil) + "[]"
		}
		return v
	case []any:
		var s []string
		for _, x := range v {
			if x != "null" {
				s = append(s, fmt.Sprint(x))
			}
		}
		return strings.Join(s, " | ")
	}
	return ""
}

func mcpPage(data []byte) (string, error) {
	var l mcpList
	if err := json.Unmarshal(data, &l); err != nil {
		return "", err
	}
	if len(l.Tools) < 20 {
		return "", fmt.Errorf("only %d MCP tools listed", len(l.Tools))
	}
	var b strings.Builder
	b.WriteString(frontmatter("MCP reference", "Every tool Hammock's MCP server (hmk mcp) gives agents, and its parameters.", 5))
	b.WriteString(generated)
	b.WriteString("`hmk mcp` is an MCP server, run by your agent over stdio, that lets it see and drive your workspace. ")
	b.WriteString("`hmk hooks install` registers it with the agents that take one; see [Controlling Hammock from agents](/hammock/docs/agents/mcp/) to set it up and for what agents may do. ")
	b.WriteString("Tools for a kind of pane switched off in Settings ▸ Tools (`browser-enabled = false`, and so on) aren't offered.\n\n")
	b.WriteString("## What the server tells agents\n\nAgents read these instructions when they connect (every kind of pane on):\n\n")
	b.WriteString("> " + text(l.Instructions) + "\n\n")
	for _, g := range mcpGroups {
		var tools []int
		for i, t := range l.Tools {
			if t.Group == g.id {
				tools = append(tools, i)
			}
		}
		if len(tools) == 0 {
			continue
		}
		fmt.Fprintf(&b, "## %s\n\n%s\n\n", g.title, g.blurb)
		sort.Slice(tools, func(i, j int) bool { return l.Tools[tools[i]].Name < l.Tools[tools[j]].Name })
		for _, i := range tools {
			t := l.Tools[i]
			fmt.Fprintf(&b, "### %s\n\n%s\n\n", t.Name, text(sentence(t.Description)))
			props := t.InputSchema.Properties
			if len(props) == 0 {
				b.WriteString("No parameters.\n\n")
				continue
			}
			names := make([]string, 0, len(props))
			for n := range props {
				names = append(names, n)
			}
			req := t.InputSchema.Required
			// Required first, then by name.
			sort.Slice(names, func(i, j int) bool {
				ri, rj := slices.Contains(req, names[i]), slices.Contains(req, names[j])
				if ri != rj {
					return ri
				}
				return names[i] < names[j]
			})
			b.WriteString("| Parameter | Type | Required | Description |\n|---|---|---|---|\n")
			for _, n := range names {
				p := props[n]
				r := ""
				if slices.Contains(req, n) {
					r = "✓"
				}
				fmt.Fprintf(&b, "| `%s` | %s | %s | %s |\n", n, cell(typeName(p.Type, p.Items)), r, cell(sentence(p.Description)))
			}
			b.WriteString("\n")
		}
	}
	return b.String(), nil
}

// ---- Keyboard shortcuts

func shortcutsPage(data []byte) (string, error) {
	var d struct {
		Groups  []string `json:"groups"`
		Actions []struct {
			ID, Title, Group string
			Shortcut, Config *string
		} `json:"actions"`
	}
	if err := json.Unmarshal(data, &d); err != nil {
		return "", err
	}
	if len(d.Actions) < 20 {
		return "", fmt.Errorf("only %d keybind actions", len(d.Actions))
	}
	var b strings.Builder
	b.WriteString(frontmatter("Keyboard shortcuts", "The Mac app's default keyboard shortcuts, and every action you can give one.", 1))
	b.WriteString(generated)
	b.WriteString("These are the Mac app's defaults, grouped as in Settings ▸ Keyboard. Every action can be given a shortcut, or have its own taken away, ")
	b.WriteString("in Settings ▸ Keyboard or with `keybind` lines in the [config file](/hammock/docs/reference/config/#keybind), using the action's name:\n\n")
	b.WriteString("```ini\n# Give an action a shortcut\nkeybind = ctrl+cmd+b=new_browser_tab\n# Take an action's shortcut away\nkeybind = none=new_tab\n# Free a shortcut\nkeybind = cmd+j=unbind\n```\n\n")
	b.WriteString("The Simulator and Editor actions work only while that kind of pane is focused, so they can share keys with each other. ")
	b.WriteString("`hmk tui` has its own keys: see [The TUI](/hammock/docs/tui/#keys).\n\n")
	for _, g := range d.Groups {
		fmt.Fprintf(&b, "## %s\n\n| Action | Default | Name |\n|---|---|---|\n", g)
		for _, a := range d.Actions {
			if a.Group != g {
				continue
			}
			sc := "–"
			if a.Shortcut != nil {
				sc = "<kbd>" + cell(*a.Shortcut) + "</kbd>"
			}
			fmt.Fprintf(&b, "| %s | %s | `%s` |\n", cell(a.Title), sc, a.ID)
		}
		b.WriteString("\n")
	}
	return b.String(), nil
}
