#!/bin/sh
# Regenerates apple/Sources/HammockKit/EmojiData.swift (the emoji picker's
# list, for a linked computer's icon) from Unicode's emoji-test.txt:
# fully-qualified emoji, by group, without skin-tone variants or the
# Component group. Usage: scripts/emoji-data.sh [version] (default 16.0).
set -eu
v=${1:-16.0}
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
curl -fsSL "https://unicode.org/Public/emoji/$v/emoji-test.txt" -o "$tmp/emoji-test.txt"
out=apple/Sources/HammockKit/EmojiData.swift
{
  echo "// Generated by scripts/emoji-data.sh from Unicode's emoji-test.txt (Emoji $v): don't edit."
  echo "// Lines: \"@Group\", then \"emoji<TAB>name\"."
  echo ""
  echo "let emojiData = \"\"\""
  awk -F'[;#]' '
    /^# group: /{ g = substr($0, 10); if (g != "Component") print "@" g; next }
    g == "Component" { next }
    /; fully-qualified/ {
      split($3, a, " "); e = a[1]; n = $3; sub(/^ *[^ ]+ E[0-9.]+ /, "", n)
      if (n ~ /skin tone/) next
      gsub(/\\/, "\\\\", n); gsub(/"/, "\\\"", n)
      print e "\t" n
    }' "$tmp/emoji-test.txt"
  echo "\"\"\""
} > "$out"
echo "wrote $out ($(grep -c '	' "$out") emoji)"
